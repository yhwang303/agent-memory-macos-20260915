/**
 * prepare-resume-mcp.js — 把 resume-mcp(agentMemory-resume-mcp 的 vendored 副本)的产物
 * stage 到 desktop/build-resources/resume-mcp/。
 *
 * 比 prepare-hybrid-mcp.js 简单得多,因为 agentMemory-resume-mcp 的 prod deps
 * (@modelcontextprotocol/sdk + better-sqlite3) 全部已经在 AgentMemory 主 node_modules
 * 里(hybrid 那一轮已经把它们打入 installer 的 resources/node_modules/),
 * 所以这里没有 PRIVATE_DEPS 段。
 *
 * 思路:
 *   1. 源 = <repoRoot>/resume-mcp/(主仓内 vendor 的子目录),可被环境变量
 *      AGENTMEM_RESUME_MCP_DIR 显式覆盖
 *   2. 在源目录跑一次 `npm install` + `npm run build`
 *   3. 复制 dist/ + package.json 到 build-resources/resume-mcp/
 *   4. 写一份 agentMemory-resume-mcp.cmd 模板(NSIS 安装时实际生成,这是参考)
 *
 * 失败行为: 如果 resume-mcp/ 源不可达(理论上不会,因为已 vendor 进主仓),
 * prepare:bundle 不会因此失败,而是输出警告并跳过 — 同 prepare-hybrid-mcp.js
 * 的退路逻辑。
 */
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const desktopRoot = path.join(__dirname, '..');
const repoRoot = path.join(desktopRoot, '..');
const stageRoot = path.join(desktopRoot, 'build-resources', 'resume-mcp');
// 默认从 vendored 子目录拿源码;AGENTMEM_RESUME_MCP_DIR env 可显式覆盖(开发期调试用)。
const sourceRoot = process.env.AGENTMEM_RESUME_MCP_DIR || path.join(repoRoot, 'resume-mcp');

function logInfo(msg) { console.log(`[prepare-resume-mcp] ${msg}`); }
function logWarn(msg) { console.warn(`[prepare-resume-mcp] WARN: ${msg}`); }

function buildSource() {
  const isWin = process.platform === 'win32';
  const npmCmd = isWin ? 'npm.cmd' : 'npm';

  // resume-mcp/ 是 vendored 进主仓的源码,不带 node_modules。先按需 install,
  // 主要是 typescript devDep 用来 build。如果已经有 node_modules 就跳过,
  // 加快重复构建。
  const nmDir = path.join(sourceRoot, 'node_modules');
  const tscBin = path.join(nmDir, 'typescript', 'bin', 'tsc');
  if (!fs.existsSync(tscBin)) {
    logInfo(`installing resume-mcp deps at ${sourceRoot} (first time / cache miss) ...`);
    const inst = spawnSync(npmCmd, ['install', '--no-audit', '--no-fund', '--loglevel=error'], {
      cwd: sourceRoot,
      stdio: 'inherit',
      env: process.env,
      shell: isWin,
    });
    if (inst.status !== 0) {
      throw new Error(`resume-mcp npm install failed (exit ${inst.status})`);
    }
  } else {
    logInfo('resume-mcp node_modules already present — skipping npm install');
  }

  logInfo(`building source at ${sourceRoot} ...`);
  fs.rmSync(path.join(sourceRoot, 'dist'), { recursive: true, force: true });
  const result = spawnSync(npmCmd, ['run', 'build'], {
    cwd: sourceRoot,
    stdio: 'inherit',
    env: process.env,
    shell: isWin, // npm.cmd 需要走 shell, 否则 spawnSync 在某些环境下会 exit null
  });
  if (result.status !== 0) {
    throw new Error(`resume-mcp build failed (exit ${result.status})`);
  }
}

function copyTree(src, dst) {
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.cpSync(src, dst, { recursive: true, force: true });
}

function stageDistAndPackage() {
  fs.rmSync(stageRoot, { recursive: true, force: true });
  fs.mkdirSync(stageRoot, { recursive: true });

  const distSrc = path.join(sourceRoot, 'dist');
  const distDst = path.join(stageRoot, 'dist');
  if (!fs.existsSync(distSrc)) {
    throw new Error(`dist/ missing after build: ${distSrc}`);
  }
  copyTree(distSrc, distDst);
  logInfo(`staged dist/ → ${path.relative(desktopRoot, distDst)}`);

  // package.json 是必需的 — Node ESM 需要它来识别 "type": "module"
  const pkgSrc = path.join(sourceRoot, 'package.json');
  fs.copyFileSync(pkgSrc, path.join(stageRoot, 'package.json'));
  logInfo('staged package.json');

  // README + LICENSE (best-effort,不存在也不报错)
  for (const f of ['README.md', 'LICENSE']) {
    const s = path.join(sourceRoot, f);
    if (fs.existsSync(s)) {
      fs.copyFileSync(s, path.join(stageRoot, f));
    }
  }
}

function writeWrapperTemplate() {
  // NSIS installer 安装时把这个文件拷到 ${INSTDIR}\bin\agentmem-resume-mcp.cmd 并加 PATH。
  // 这里只是参考模板;真实 wrapper 是 NSIS 在装机时按 ${INSTDIR} 生成的(见
  // desktop/build/installer.nsh),路径自适应安装位置。
  const wrapper = [
    '@echo off',
    'rem agentmem-resume-mcp launcher — generated by AgentMemory installer',
    'rem do not edit; will be overwritten on upgrade',
    '"%~dp0..\\resources\\node.exe" "%~dp0..\\resources\\resume-mcp\\dist\\server.js" %*',
    '',
  ].join('\r\n');
  const wrapperPath = path.join(stageRoot, 'agentmem-resume-mcp.cmd');
  fs.writeFileSync(wrapperPath, wrapper, 'utf8');
  logInfo('wrote wrapper template: agentmem-resume-mcp.cmd');
}

function main() {
  if (!fs.existsSync(sourceRoot)) {
    logWarn(`source not found: ${sourceRoot}`);
    logWarn('skipping agentMemory-resume-mcp staging — installer will NOT include the resume MCP bundle.');
    logWarn('Set AGENTMEM_RESUME_MCP_DIR=<path> to override.');
    fs.mkdirSync(stageRoot, { recursive: true });
    fs.writeFileSync(
      path.join(stageRoot, '.MISSING'),
      'agentMemory-resume-mcp source was not found at build time; resume MCP bundle absent.\n',
      'utf8'
    );
    return;
  }

  buildSource();
  stageDistAndPackage();
  writeWrapperTemplate();
  logInfo(`done — staged at ${stageRoot}`);
}

try {
  main();
} catch (err) {
  console.error(`[prepare-resume-mcp] FATAL: ${err.message}`);
  process.exit(1);
}
